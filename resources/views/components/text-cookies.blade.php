                        <h3 class="main_title mt-dk-100" style="text-decoration: underline;text-transform:uppercase;">Política de Cookies</h3>
                        
                        <h5 class="mt-5"><b>¿Qué son las cookies?</b></h5>
                        <p>Una cookie es cualquier tipo de dispositivo de almacenamiento y recuperación de datos que
                            se utilice en el equipo terminal de un usuario con la finalidad de almacenar información y
                            recuperar la información ya almacenada, según establece el artículo 22.2 de la Ley 34/2002,
                            de 11 de julio, de servicios de la sociedad de la información y de comercio electrónico (LSSI).</p>

                        <p>Esta plataforma utiliza cookies y/o tecnologías similares que almacenan y recuperan
                            información cuando navega. En general, estas tecnologías pueden servir para finalidades
                            muy diversas, como, por ejemplo, reconocerle como usuario, obtener información sobre sus
                            hábitos de navegación, o personalizar la forma en que se muestra el contenido. Los usos
                            concretos que hacemos de estas tecnologías se describen a continuación.</p>

                        <h5 class="mt-5"><b>Clases de cookies</b></h5>
                        <p>A continuación, se realiza una clasificación de las cookies en función de una serie de
                            categorías. No obstante, es necesario tener en cuenta que una misma cookie puede estar
                            incluida en más de una categoría.</p>
                        
                        <p style="text-decoration: underline;">Tipos de cookies según la entidad que las gestione</p>
                        <ol style="list-style-type: lower-latin;">
                            <li>Cookies propias: son aquellas que se envían al equipo terminal del usuario desde un
                                equipo o dominio gestionado por el propio editor y desde el que se presta el servicio
                                solicitado por el usuario.</li>
                            <li class="mt-2">Cookies de tercero: son aquellas que se envían al equipo terminal del usuario desde
                                un equipo o dominio que no es gestionado por el editor, sino por otra entidad que
                                trata los datos obtenidos través de las cookies.</li>
                        </ol>
                        
                        <p style="text-decoration: underline;">Tipos de cookies según su finalidad</p>
                        <ol style="list-style-type: lower-latin;">
                            <li>Cookies técnicas: son aquellas que permiten al usuario la navegación a través de una
                                página web, plataforma o aplicación y la utilización de las diferentes opciones o
                                servicios que en ella existan, incluyendo aquellas que el editor utiliza para permitir la
                                gestión y operativa de la plataforma y habilitar sus funciones y servicios, como, por
                                ejemplo, controlar el tráfico y la comunicación de datos, identificar la sesión, acceder
                                a partes de acceso restringido, recordar los elementos que integran un pedido,
                                realizar el proceso de compra de un pedido, gestionar el pago, controlar el fraude
                                vinculado a la seguridad del servicio, realizar la solicitud de inscripción o participación
                                en un evento, contar visitas a efectos de la facturación de licencias del software con el
                                que funciona el servicio (sitio web, plataforma o aplicación), utilizar elementos de
                                seguridad durante la navegación, almacenar contenidos para la difusión de vídeos o
                                sonido, habilitar contenidos dinámicos (por ejemplo, animación de carga de un texto o
                                imagen) o compartir contenidos a través de redes sociales.</li>
                            <li class="mt-2">Cookies de preferencias o personalización: son aquellas que permiten recordar
                                información para que el usuario acceda al servicio con determinadas características
                                que pueden diferenciar su experiencia de la de otros usuarios, como, por ejemplo, el
                                idioma, el número de resultados a mostrar cuando el usuario realiza una búsqueda, el
                                aspecto o contenido del servicio en función del tipo de navegador a través del cual el
                                usuario accede al servicio o de la región desde la que accede al servicio, etc.</li>
                            <li class="mt-2">Cookies de análisis o medición: son aquellas que permiten al responsable de las
                                mismas el seguimiento y análisis del comportamiento de los usuarios de la plataforma
                                a los que están vinculadas, incluida la cuantificación de los impactos de los anuncios.
                                La información recogida mediante este tipo de cookies se utiliza en la medición de la
                                actividad de los sitios web, aplicación o plataforma, con el fin de introducir mejoras en
                                función del análisis de los datos de uso que hacen los usuarios del servicio.</li>
                            <li class="mt-2">Cookies de publicidad comportamental: son aquellas que almacenan información del
                                comportamiento de los usuarios obtenida a través de la observación continuada de
                                sus hábitos de navegación, lo que permite desarrollar un perfil específico para
                                mostrar publicidad en función del mismo.</li>
                        </ol>

                        <p style="text-decoration: underline;">Tipos de cookies según el plazo de tiempo que permanecen activadas</p>
                        <ol style="list-style-type: lower-latin;">
                            <li>Cookies de sesión: son aquellas diseñadas para recabar y almacenar datos mientras el
                                usuario accede a una página web. Se suelen emplear para almacenar información que
                                solo interesa conservar para la prestación del servicio solicitado por el usuario en una
                                sola ocasión y desaparecen al terminar la sesión.</li>
                            <li class="mt-2">Cookies persistentes: son aquellas en las que los datos siguen almacenados en el
                                terminal y pueden ser accedidos y tratados durante un periodo definido por el
                                responsable de la cookie.</li>
                        </ol>

